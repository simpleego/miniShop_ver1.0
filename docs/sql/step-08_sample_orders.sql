-- 주문 당시 가격 = 현재 상품 가격으로 채우기
UPDATE order_items oi
JOIN products p ON p.id = oi.product_id
SET oi.unit_price = p.price;

-- 주문 총액 = 주문 상품 (수량 × 단가) 합계
UPDATE orders o
JOIN (
  SELECT order_id, SUM(quantity * unit_price) AS total
  FROM order_items
  GROUP BY order_id
) t ON t.order_id = o.id
SET o.total_price = t.total;

-- 구매(PAID) 주문의 결제 시각 = 주문 시각 (구매내역 조회는 paid_at 기준)
UPDATE orders SET paid_at = created_at WHERE status = 'PAID';

-- 예상 결과 : 판매 인기순 1위 생수 500ml(40개) > 콜라(35개) > 아메리카노(28개) > 바나나우유(20개) > 사이다(15개)
SELECT p.name, SUM(oi.quantity) AS sold_qty
FROM order_items oi
JOIN orders o   ON o.id = oi.order_id AND o.status = 'PAID'
JOIN products p ON p.id = oi.product_id AND p.is_active = 1
GROUP BY p.id, p.name
ORDER BY sold_qty DESC
LIMIT 5;
